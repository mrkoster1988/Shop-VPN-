def run(args, **kwargs):
    return subprocess.run(args, check=True, **kwargs)


def atomic_text(path, text, mode=0o600):
    path=Path(path)
    fd,temp=tempfile.mkstemp(prefix='.pushok-',dir=path.parent)
    try:
        with os.fdopen(fd,'w') as stream:
            os.fchmod(stream.fileno(),mode);stream.write(text);stream.flush();os.fsync(stream.fileno())
        if path.exists():
            stat=path.stat();os.chmod(temp,stat.st_mode & 0o777)
            if os.geteuid()==0: os.chown(temp,stat.st_uid,stat.st_gid)
        os.replace(temp,path)
    finally:
        if os.path.exists(temp):os.unlink(temp)


def public_url(value):
    message='Нужен HTTPS-адрес на вашем домене без порта, например https://example.com/shop'
    try:
        p=urlsplit(value.strip().rstrip('/'))
        host=p.hostname.encode('idna').decode('ascii').lower() if p.hostname else ''
        labels=host.split('.')
        if (p.scheme!='https' or not host or p.username or p.password or p.query or p.fragment
                or p.netloc.lower()!=p.hostname or len(host)>253 or len(labels)<2
                or any(not re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?',label) for label in labels)
                or not re.fullmatch(r'(?:/[A-Za-z0-9_-]+)+',p.path)):
            raise ValueError()
        return 'https://'+host+p.path
    except (ValueError,UnicodeError,AttributeError):
        raise ValueError(message) from None


def choose_public_url(value):
    if value:return public_url(value)
    while True:
        candidate=ask('Адрес магазина на вашем домене (например https://example.com/shop)')
        try:return public_url(candidate)
        except ValueError as error:print(str(error))


def install_path(value):
    p=Path(value)
    if not p.is_absolute() or not re.fullmatch(r'/[A-Za-z0-9_/-]+',str(p)) or str(p) in ('/','/opt','/etc','/usr','/var','/root'):
        raise ValueError('Укажите отдельный абсолютный каталог, например /opt/pushok-vpn')
    resolved=p.resolve()
    if str(resolved) in ('/','/opt','/etc','/usr','/var','/root'):raise ValueError('Нужен отдельный каталог')
    return resolved


def check_os(info=None):
    info=info or platform.freedesktop_os_release()
    if info.get('ID')!='ubuntu' or info.get('VERSION_ID') not in ('22.04','24.04'):
        raise ValueError('Установщик поддерживает Ubuntu 22.04 и 24.04 LTS')
    return {'22.04':'jammy','24.04':'noble'}[info['VERSION_ID']]


def port_free(port,host='0.0.0.0'):
    try:
        with socket.socket() as sock:sock.bind((host,port))
        return True
    except OSError:return False


def quote_env(value):
    if any(ord(ch)<32 for ch in value):raise ValueError('Переносы строк и управляющие символы недопустимы')
    return "'"+value.replace('\\','\\\\').replace("'","\\'")+"'"


def environment(settings, bot_token='',bot_username='',terms=''):
    if bot_token and not re.fullmatch(r'[0-9]+:[A-Za-z0-9_-]+',bot_token):raise ValueError('Некорректный токен Telegram')
    if bot_username and not re.fullmatch(r'[A-Za-z0-9_]{5,32}',bot_username):raise ValueError('Некорректное имя бота')
    values={'PUBLIC_URL':settings['url'],'ADMIN_TOKEN':secrets.token_urlsafe(48),
        'ENCRYPTION_KEY':base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
        'BOT_TOKEN':bot_token,'BOT_USERNAME':bot_username,'TERMS_TEXT':terms,
        'PARTNER_PROMO_CODE':'','PARTNER_WEBHOOK_SECRET':'',
        'SUPPORT_TEXT':settings['support'],'PAYMENT_MODE':'manual',
        'MANUAL_PAYMENT_TEXT':'Обратитесь в поддержку и сообщите номер заказа. '+settings['support'],
        'YOOKASSA_RECEIPTS':'false','WG_AGENT_TOKEN':secrets.token_urlsafe(48)}
    return ''.join(key+'='+quote_env(value)+'\n' for key,value in values.items())


def nginx_routes(url,port):
    path=urlsplit(url).path
    headers='''        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;'''
    return f'''# Generated by Shop VPN installer. Include inside the existing HTTPS server.
location = {path} {{ return 308 {path}/$is_args$args; }}
location = {path}/login {{
        access_log off;
        proxy_pass http://127.0.0.1:{port};
{headers}
}}
location ^~ {path}/sub/ {{
        access_log off;
        error_log /dev/null crit;
        proxy_pass http://127.0.0.1:{port};
{headers}
}}
location ^~ {path}/ {{
        client_max_body_size 16k;
        proxy_pass http://127.0.0.1:{port};
{headers}
}}
'''


def nginx_insert(text,domain,include,path):
    marker='include '+str(include)+';'
    # Разбираем только обычные блоки server; неоднозначные шаблоны отклоняем.
    if '${' in text:raise ValueError('Шаблонная конфигурация Nginx: используйте режим external')
    tokens=list(re.finditer(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|\#[^\n]*|[{};]|[^\s{};#]+',text))
    stack=[];statement=[];candidates=[]
    for token in tokens:
        value=token.group()
        if value.startswith('#'):continue
        if value=='{':
            stack.append({'name':statement[:],'directives':[],'start':token.start()});statement=[]
        elif value==';':
            if stack:stack[-1]['directives'].append(statement[:])
            statement=[]
        elif value=='}':
            if not stack:raise ValueError('Некорректные скобки Nginx')
            block=stack.pop();statement=[]
            if block['name']==['server']:
                directives=block['directives']
                names=[item.strip('"\'') for line in directives if line[:1]==['server_name'] for item in line[1:]]
                tls=any(line[:1]==['listen'] and 'ssl' in line and any(x=='443' or x.endswith(':443') for x in line[1:]) for line in directives)
                if domain in names and tls:candidates.append((block,token.start()))
            if stack:stack[-1]['directives'].append(block['name'])
        else:statement.append(value)
    if stack or len(candidates)!=1:raise ValueError('Нужен ровно один HTTPS server с указанным server_name в выбранном файле')
    block,end=candidates[0]
    segment=text[block['start']:end]
    if any(line==['include',str(include)] for line in block['directives']):return text
    for line in block['directives']:
        if line[:1]==['location'] and any(x.strip('"\'').rstrip('/')==path for x in line[1:]):
            raise ValueError('Маршруты магазина уже существуют: используйте режим external')
    return text[:end]+'    '+marker+'\n'+text[end:]


def attach_nginx(config,settings,root):
    config=Path(config).resolve(strict=True)
    run(['nginx','-t'])
    original=config.read_text()
    updated=nginx_insert(original,urlsplit(settings['url']).hostname,root/'nginx.shop.conf',urlsplit(settings['url']).path)
    if updated==original:return
    backups=root/'backups';backups.mkdir(exist_ok=True,mode=0o700)
    atomic_text(backups/('nginx-'+str(time.time_ns())+'.conf'),original)
    atomic_text(config,updated)
    try:
        run(['nginx','-t']);run(['systemctl','reload','nginx'])
    except Exception:
        atomic_text(config,original)
        with contextlib.suppress(Exception):run(['nginx','-t']);run(['systemctl','reload','nginx'])
        raise RuntimeError('Nginx не принял изменения; исходный файл восстановлен') from None



def caddy_config(domain,path,port):
    return '\n'.join(['{','    log default {','        format filter {','            wrap json',
        '            fields {','                request>uri replace REDACTED','            }',
        '        }','    }','}',f'{domain} {{',f'    @private_shop path {path}/login {path}/sub/*',
        '    log_skip @private_shop',f'    @bare path {path}',f'    redir @bare {path}/ 308',
        f'    handle {path}/* {{',f'        reverse_proxy 127.0.0.1:{port}','    }','    respond 404','}',''])

def compose(settings,root):
    port=settings['port']
    data={'services':{'shop':{'build':str(root/'source'),'restart':'unless-stopped',
        'env_file':[str(root/'.env')],'environment':{'DATA_DIR':'/app/data'},'network_mode':'host',
        'volumes':['shop_data:/app/data'],'read_only':True,'tmpfs':['/tmp'],'cap_drop':['ALL'],
        'security_opt':['no-new-privileges:true'],
        'command':['python','-m','uvicorn','app.main:app','--host','127.0.0.1','--port',str(port),'--workers','1','--no-access-log'],
        'healthcheck':{'test':['CMD','python','-c',f"import urllib.request; urllib.request.urlopen('http://127.0.0.1:{port}{urlsplit(settings['url']).path}/health',timeout=5)"],
                       'interval':'10s','timeout':'8s','retries':6}}},'volumes':{'shop_data':{}}}
    if settings['mode']=='caddy':
        data['services']['https']={'image':'caddy:2','restart':'unless-stopped','network_mode':'host',
            'volumes':[str(root/'Caddyfile')+':/etc/caddy/Caddyfile:ro','caddy_data:/data','caddy_config:/config']}
        data['volumes'].update(caddy_data={},caddy_config={})
    return json.dumps(data,indent=2)+'\n'


def docker_ready(codename):
    if shutil.which('docker'):
        run(['docker','compose','version']);run(['docker','info'],stdout=subprocess.DEVNULL)
        return
    # Не удаляем чужой движок или среду контейнеров ради установки.
    for package in ('docker.io','docker-compose','docker-compose-v2','containerd','containerd.io','runc','podman-docker'):
        r=subprocess.run(['dpkg-query','-W','-f=${Status}',package],capture_output=True,text=True)
        if r.returncode==0 and 'install ok installed' in r.stdout:
            raise RuntimeError('Обнаружен контейнерный runtime. Настройте Docker + Compose v2 отдельно; пакеты не удалены.')
    run(['apt-get','update']);run(['apt-get','install','-y','ca-certificates'])
    keydir=Path('/etc/apt/keyrings');keydir.mkdir(mode=0o755,exist_ok=True)
    key=keydir/'pushok-docker.asc';repo=Path('/etc/apt/sources.list.d/pushok-docker.sources')
    with urlopen('https://download.docker.com/linux/ubuntu/gpg',timeout=30) as response:keydata=response.read(128000).decode()
    if not keydata.startswith('-----BEGIN PGP PUBLIC KEY BLOCK-----'):raise RuntimeError('Некорректный ключ репозитория Docker')
    atomic_text(key,keydata,0o644)
    arch=run(['dpkg','--print-architecture'],capture_output=True,text=True).stdout.strip()
    if arch not in ('amd64','arm64'):raise ValueError('Поддерживаются amd64 и arm64')
    atomic_text(repo,f'Types: deb\nURIs: https://download.docker.com/linux/ubuntu\nSuites: {codename}\nComponents: stable\nArchitectures: {arch}\nSigned-By: {key}\n',0o644)
    run(['apt-get','update']);run(['apt-get','install','-y','docker-ce','docker-ce-cli','containerd.io','docker-buildx-plugin','docker-compose-plugin'])
    run(['systemctl','enable','--now','docker']);run(['docker','compose','version'])


def ask(label,default='',secret=False):
    with open('/dev/tty','r+') as tty:
        if secret:return getpass.getpass(label+': ',stream=tty)
        tty.write(label+(f' [{default}]' if default else '')+': ');tty.flush()
        answer=tty.readline()
        if not answer:raise ValueError('Диалог прерван')
        return answer.strip() or default


def wait_health(url,timeout=120):
    deadline=time.monotonic()+timeout
    while time.monotonic()<deadline:
        try:
            with urlopen(url,timeout=5) as response:
                if response.status==200 and json.loads(response.read(4096)).get('status')=='ok':return
        except Exception:pass
        time.sleep(2)
    raise RuntimeError('Проверка доступности не прошла: '+url+'. Проверьте DNS, HTTPS и контейнеры; конфигурация сохранена для повтора.')


def parser():
    p=argparse.ArgumentParser(description='Установка Shop VPN одной командой')
    p.add_argument('--source',type=Path,default=Path(__file__).resolve().parents[1]);p.add_argument('--dir',default='/opt/pushok-vpn')
    p.add_argument('--url');p.add_argument('--mode',choices=['caddy','nginx','external']);p.add_argument('--nginx-config')
    p.add_argument('--port',type=int);p.add_argument('--support');p.add_argument('--yes',action='store_true')
    p.add_argument('--plan',action='store_true',help='Показать план без изменений и секретов')
    return p


def main(argv=None):
    args=parser().parse_args(argv);root=install_path(args.dir);codename=check_os()
    marker=root/'installer.json'
    if marker.exists():
        settings=json.loads(marker.read_text())
        if settings.get('managed_upgrade'):raise ValueError('Установка обновлена через upgrade.py; используйте status/activate/rollback, не повторный установщик')
        if settings.get('version')!=VERSION:raise ValueError('Другая версия уже установлена. Автоматическое обновление с миграцией не выполняется.')
        for key in ('url','mode','port','support','nginx_config'):
            supplied=getattr(args,key,None)
            if key=='url' and supplied is not None:supplied=public_url(supplied)
            if supplied is not None and supplied!=settings.get(key):raise ValueError('Повторный запуск сохраняет параметры; не меняйте '+key)
    else:
        if root.exists() and any(p.name!='.install.lock' for p in root.iterdir()):raise ValueError('Каталог не пуст и не принадлежит установщику. Существующая установка не изменена.')
        if args.yes and (not args.url or not args.mode):raise ValueError('--yes требует --url и --mode')
        url=choose_public_url(args.url)
        mode=args.mode or ask('Режим: caddy (новый HTTPS), nginx (существующий сайт), external (другой прокси)','nginx' if shutil.which('nginx') else 'caddy')
        if mode not in ('caddy','nginx','external'):raise ValueError('Неизвестный режим')
        port=args.port or int(ask('Внутренний порт магазина','8000') if not args.yes else '8000')
        if not 1024<=port<=65535:raise ValueError('Порт должен быть от 1024 до 65535')
        config=args.nginx_config
        if mode=='nginx':
            config=config or (ask('Путь к файлу существующего HTTPS-сайта Nginx') if not args.yes else '')
            if not config or not Path(config).is_file():raise ValueError('Нужен --nginx-config с существующим HTTPS-сайтом')
            nginx_insert(Path(config).read_text(),urlsplit(url).hostname,root/'nginx.shop.conf',urlsplit(url).path)
        settings={'version':VERSION,'url':url,'mode':mode,'port':port,'nginx_config':config,
                  'support':args.support if args.support is not None else (ask('Контакт поддержки','Поддержка уточняется') if not args.yes else 'Поддержка уточняется'),
                  'project':'pushok-'+hashlib.sha256(str(root).encode()).hexdigest()[:10]}
    print('Shop VPN '+VERSION+' → '+settings['url']+'\nКаталог: '+str(root)+'\nРежим: '+settings['mode']+'; порт: '+str(settings['port']))
    if args.plan:return 0
    if os.geteuid()!=0:raise ValueError('Нужны права root')
    if not (args.source/'scripts/install.py').is_file() or not (args.source/'Dockerfile').is_file():
        raise ValueError('Нужен полный каталог исходников установки')
    if root==args.source.resolve() or args.source.resolve() in root.parents:
        raise ValueError('Каталог установки не должен находиться внутри исходников')
    if not marker.exists():
        if not port_free(settings['port']):raise ValueError('Внутренний порт занят. Выберите другой --port')
        if settings['mode']=='caddy' and (not port_free(80) or not port_free(443)):
            raise ValueError('80/443 заняты. Используйте nginx или external; работающий сайт не остановлен.')
    root.mkdir(parents=True,exist_ok=True,mode=0o700)
    lock=open(root/'.install.lock','w')
    try:fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
    except BlockingIOError:raise RuntimeError('Установка уже выполняется') from None
    with lock:
        fresh=not marker.exists()
        if fresh:
            atomic_text(marker,json.dumps(settings,indent=2)+'\n')
        if not (root/'source').exists():
            staging=root/'.source-staging'
            if staging.exists():
                if staging.is_symlink():raise ValueError('Некорректный staging-каталог')
                shutil.rmtree(staging)
            shutil.copytree(args.source,staging,ignore=shutil.ignore_patterns('.git','.env','.env.*','data','.venv','__pycache__','.pytest_cache','*.zip','backups','upgrades','*.pvb','*.db','*.db-wal','*.db-shm'))
            staging.rename(root/'source')
        if not (root/'source/scripts/install.py').is_file():raise ValueError('Неполные исходники; восстановите резервную копию')
        if not (root/'.env').exists():
            bot='';username='';terms=''
            if not args.yes:
                bot=ask('Токен Telegram-бота (Enter — настроить позже)',secret=True)
                if bot:
                    username=ask('Имя бота без @');terms=ask('Условия продажи для Telegram (можно настроить позже)')
            atomic_text(root/'.env',environment(settings,bot,username,terms))
        else:os.chmod(root/'.env',0o600)
        atomic_text(root/'compose.install.json',compose(settings,root))
        atomic_text(root/'nginx.shop.conf',nginx_routes(settings['url'],settings['port']))
        domain=urlsplit(settings['url']).hostname;path=urlsplit(settings['url']).path
        atomic_text(root/'Caddyfile',caddy_config(domain,path,settings['port']))
        docker_ready(codename)
        command=['docker','compose','--project-name',settings['project'],'--env-file',str(root/'.env'),'-f',str(root/'compose.install.json')]
        run(command+['up','-d','--build','--wait','--wait-timeout','120'])
        wait_health(f'http://127.0.0.1:{settings["port"]}{path}/health')
        if settings['mode']=='nginx':attach_nginx(settings['nginx_config'],settings,root)
        if settings['mode']=='external':
            print('Магазин запущен локально. HTTPS пока не подключён.\nДобавьте маршруты из '+str(root/'nginx.shop.conf')+' в существующий прокси.\nПосле настройки проверьте '+settings['url']+'/health')
            return 2
        wait_health(settings['url']+'/health',180)
        print('Готово: '+settings['url']+'/\nАдминка: '+settings['url']+'/admin\nКлюч ADMIN_TOKEN сохранён в '+str(root/'.env')+' (0600).\nДобавьте VPN-серверы в админке. Платежи и реальный VPN проверьте перед продажами.')
        return 0

if __name__=='__main__':
    try:raise SystemExit(main())
    except (ValueError,RuntimeError,OSError,subprocess.CalledProcessError) as exc:
        print('Установка остановлена: '+str(exc),file=__import__('sys').stderr);raise SystemExit(1)
